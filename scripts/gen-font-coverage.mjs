// Generates src/engine/font-coverage.ts: the code point ranges present in all four bundled Roboto faces.
import { openSync } from "fontkit";
import { writeFileSync } from "node:fs";

const dir = "node_modules/pdfmake/fonts/Roboto/";
const faces = ["Roboto-Regular.ttf", "Roboto-Medium.ttf", "Roboto-Italic.ttf", "Roboto-MediumItalic.ttf"];
let common = null;
for (const f of faces) {
  const set = new Set(openSync(dir + f).characterSet);
  common = common ? new Set([...common].filter((c) => set.has(c))) : set;
}
const cps = [...common].sort((a, b) => a - b);
const ranges = [];
for (const cp of cps) {
  const last = ranges[ranges.length - 1];
  if (last && cp === last[1] + 1) last[1] = cp;
  else ranges.push([cp, cp]);
}
const body = ranges.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(",");
writeFileSync(
  "src/engine/font-coverage.ts",
  `// Generated by scripts/gen-font-coverage.mjs. Do not edit.\n/** Code point ranges [start, end] supported by the bundled PDF font. */\nexport const FONT_RANGES: ReadonlyArray<readonly [number, number]> = [${body}];\n`,
);
console.log(ranges.length, "ranges;", cps.length, "glyphs");
