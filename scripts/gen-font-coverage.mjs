// Generates src/engine/font-coverage.ts: per family, the code point ranges present in all four bundled faces.
import { openSync } from "fontkit";
import { writeFileSync } from "node:fs";

const families = {
  sans: ["node_modules/pdfmake/fonts/Roboto/", ["Roboto-Regular.ttf", "Roboto-Medium.ttf", "Roboto-Italic.ttf", "Roboto-MediumItalic.ttf"]],
  serif: ["public/fonts/", ["LiberationSerif-Regular.ttf", "LiberationSerif-Bold.ttf", "LiberationSerif-Italic.ttf", "LiberationSerif-BoldItalic.ttf"]],
  mono: ["public/fonts/", ["LiberationMono-Regular.ttf", "LiberationMono-Bold.ttf", "LiberationMono-Italic.ttf", "LiberationMono-BoldItalic.ttf"]],
};

function rangesFor(dir, faces) {
  let common = null;
  for (const f of faces) {
    const set = new Set(openSync(dir + f).characterSet);
    common = common ? new Set([...common].filter((c) => set.has(c))) : set;
  }
  const cps = [...common].sort((a, b) => a - b);
  const ranges = [];
  for (const cp of cps) {
    const last = ranges[ranges.length - 1];
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return { ranges, common };
}

let out = "// Generated by scripts/gen-font-coverage.mjs. Do not edit.\n/** Code point ranges [start, end] supported by every face of each bundled PDF font family. */\nexport const FONT_RANGES: Record<\"sans\" | \"serif\" | \"mono\", ReadonlyArray<readonly [number, number]>> = {\n";
for (const [name, [dir, faces]] of Object.entries(families)) {
  const { ranges, common } = rangesFor(dir, faces);
  out += `  ${name}: [${ranges.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(",")}],\n`;
  const has = (c) => common.has(c.codePointAt(0));
  console.log(name, ranges.length, "ranges;", common.size, "glyphs", { cyrillic: has("Ж"), macedonian: has("ќ"), greek: has("λ"), bullet: has("•"), box: has("☐"), check: has("☑"), arrow: has("→"), cjk: has("中") });
}
out += "};\n";
writeFileSync("src/engine/font-coverage.ts", out);
